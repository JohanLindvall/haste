/*
 * Emits the reference results every test in this repository is measured
 * against: ../xxh3/vectors_test.go for XXH3, and with the argument "xxh64",
 * ../xxh64/vectors_test.go for XXH64. They come from the C implementation,
 * not from another Go port, so a shared misreading of the spec cannot hide
 * here.
 *
 *   git clone --depth 1 --branch v0.8.3 https://github.com/Cyan4973/xxHash
 *   cc -O2 -IxxHash -o gen gen.c
 *   ./gen > ../xxh3/vectors_test.go
 *   ./gen xxh64 > ../xxh64/vectors_test.go
 *
 * The input buffer is built exactly as xsum_sanity_check.c builds its own, so
 * a vector here can be compared against upstream's by hand.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define XXH_STATIC_LINKING_ONLY
#define XXH_IMPLEMENTATION
#include "xxhash.h"

#define PRIME32 2654435761U
#define PRIME64 11400714785074694797ULL

static void fillBuf(unsigned char* b, size_t len) {
    unsigned long long g = PRIME32;
    size_t i;
    for (i = 0; i < len; i++) { b[i] = (unsigned char)(g >> 56); g *= PRIME64; }
}

/* lengths: every length 0..300, then a spread up to 1<<21 covering block edges */
static int lengths(size_t* lens) {
    int nl = 0;
    for (size_t i = 0; i <= 300; i++) lens[nl++] = i;
    size_t extra[] = {
        511,512,513, 1023,1024,1025, 1087,1088,1089, 2047,2048,2049,
        4095,4096,4097, 8191,8192,8193, 16384, 65535,65536,65537,
        100000, 262144, 1048576, 2097151, 2097152
    };
    for (size_t i = 0; i < sizeof(extra)/sizeof(extra[0]); i++) lens[nl++] = extra[i];
    return nl;
}

static unsigned long long seeds[] = {0, 1, 0x9E3779B185EBCA87ULL, 0xFFFFFFFFFFFFFFFFULL};

/* XXH64: the same buffer, lengths and seeds, one 64-bit result each. */
static int genXXH64(const unsigned char* buf) {
    size_t lens[4096]; int nl = lengths(lens);
    printf("// Code generated by ref/gen.c from xxHash v0.8.3. DO NOT EDIT.\n\n");
    printf("package xxh64\n\n");
    printf("// refVec is one reference result: the XXH64 of the first Len bytes of the\n");
    printf("// canonical test buffer, under Seed.\n");
    printf("type refVec struct {\n\tLen  int\n\tSeed uint64\n\tH64  uint64\n}\n\n");
    printf("var refVecs = []refVec{\n");
    for (int li = 0; li < nl; li++) {
        for (unsigned si = 0; si < sizeof(seeds)/sizeof(seeds[0]); si++) {
            size_t len = lens[li]; unsigned long long seed = seeds[si];
            if (si > 0 && len > 4200 && len != 65536 && len != 1048576) continue;
            XXH64_hash_t h64 = XXH64(buf, len, seed);
            printf("\t{%zu, 0x%016llx, 0x%016llx},\n", len, seed, (unsigned long long)h64);
        }
    }
    printf("}\n");
    return 0;
}

int main(int argc, char** argv) {
    size_t const maxLen = 1u << 21;
    unsigned char* buf = malloc(maxLen);
    unsigned char secret[2048];
    fillBuf(buf, maxLen);
    if (argc > 1 && strcmp(argv[1], "xxh64") == 0) { int r = genXXH64(buf); free(buf); return r; }
    /* a custom secret, distinct from kSecret, filled with a different stream */
    { unsigned long long g = 0x9E3779B97F4A7C15ULL; size_t i;
      for (i = 0; i < sizeof secret; i++) { secret[i] = (unsigned char)(g >> 56); g *= PRIME64; g += 0x2545F4914F6CDD1DULL; } }

    printf("// Code generated by ref/gen.c from xxHash v0.8.3. DO NOT EDIT.\n\n");
    printf("package xxh3\n\n");
    printf("// refVec is one reference result: the hash of the first Len bytes of the\n");
    printf("// canonical test buffer, under Seed.\n");
    printf("type refVec struct {\n\tLen  int\n\tSeed uint64\n\tH64  uint64\n\tLo   uint64\n\tHi   uint64\n}\n\n");

    size_t lens[4096]; int nl = lengths(lens);

    printf("var refVecs = []refVec{\n");
    for (int li = 0; li < nl; li++) {
        for (unsigned si = 0; si < sizeof(seeds)/sizeof(seeds[0]); si++) {
            size_t len = lens[li]; unsigned long long seed = seeds[si];
            if (si > 0 && len > 4200 && len != 65536 && len != 1048576) continue;
            XXH64_hash_t h64 = seed ? XXH3_64bits_withSeed(buf, len, seed) : XXH3_64bits(buf, len);
            XXH128_hash_t h128 = seed ? XXH3_128bits_withSeed(buf, len, seed) : XXH3_128bits(buf, len);
            printf("\t{%zu, 0x%016llx, 0x%016llx, 0x%016llx, 0x%016llx},\n",
                   len, seed, (unsigned long long)h64,
                   (unsigned long long)h128.low64, (unsigned long long)h128.high64);
        }
    }
    printf("}\n\n");

    /* custom-secret vectors: secret lengths that change nbStripesPerBlock */
    printf("// refSecretVec is a result under a custom secret: the first SecretLen bytes\n");
    printf("// of the canonical secret buffer, over the first Len bytes of input.\n");
    printf("type refSecretVec struct {\n\tLen       int\n\tSecretLen int\n\tH64       uint64\n\tLo        uint64\n\tHi        uint64\n}\n\n");
    printf("var refSecretVecs = []refSecretVec{\n");
    size_t slens[] = {136, 137, 144, 191, 192, 193, 256, 512, 1024, 2048};
    size_t ilens[] = {0,1,7,8,16,17,32,64,100,128,129,200,240,241,256,300,512,1024,1025,2048,4096,10000,65536};
    for (size_t sj = 0; sj < sizeof(slens)/sizeof(slens[0]); sj++) {
        for (size_t ij = 0; ij < sizeof(ilens)/sizeof(ilens[0]); ij++) {
            size_t sl = slens[sj], il = ilens[ij];
            XXH64_hash_t h64 = XXH3_64bits_withSecret(buf, il, secret, sl);
            XXH128_hash_t h128 = XXH3_128bits_withSecret(buf, il, secret, sl);
            printf("\t{%zu, %zu, 0x%016llx, 0x%016llx, 0x%016llx},\n", il, sl,
                   (unsigned long long)h64, (unsigned long long)h128.low64, (unsigned long long)h128.high64);
        }
    }
    printf("}\n");
    free(buf);
    return 0;
}
