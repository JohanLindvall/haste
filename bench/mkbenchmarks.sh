#!/usr/bin/env bash
# Compose benchmarks.md from the artifacts of a bench workflow run.
#
#	bench/mkbenchmarks.sh <artifact-dir> > benchmarks.md
#
# <artifact-dir> holds one directory per runner, named bench-<runner>, as
# actions/download-artifact leaves them. Each carries cpu.txt and the tables
# mdtable rendered. Runners that produced nothing are listed rather than
# silently dropped: a missing row is a result too.
set -euo pipefail

dir=${1:?usage: mkbenchmarks.sh <artifact-dir>}
sha=${GITHUB_SHA:-$(git rev-parse HEAD 2>/dev/null || echo unknown)}
run=${GITHUB_RUN_ID:-}
repo=${GITHUB_REPOSITORY:-JohanLindvall/xxhaste}
when=${BENCH_DATE:-$(date -u +%Y-%m-%d)}

cat <<EOF
# Benchmarks

Generated by \`.github/workflows/bench.yml\` on $when, from
\`${sha:0:7}\`$( [ -n "$run" ] && echo " ([run](https://github.com/$repo/actions/runs/$run))" ).
Do not edit: the workflow overwrites this file.

Every number is nanoseconds per operation, the median of the run's
repetitions, lower better; the best cell in each row is bold. **These are
shared GitHub runner VMs**, so they are useful for shape and for ratios
between implementations measured in the same column, and not as absolute
figures. The README's tables come from dedicated hardware.

Where a C toolchain was present the columns \`c\` and \`c-xxh64\` are the
reference implementation itself, compiled from the vendored \`xxhash.h\`
(v0.8.3). Its one-shot rows cross the cgo boundary once per hash, which is an
overhead floor of tens of nanoseconds -- read those columns from a few hundred
bytes up, and the streaming rows anywhere, since they run their whole loop in C.
EOF

found=0
missing=()
for d in "$dir"/bench-*/; do
	[ -d "$d" ] || continue
	runner=$(basename "$d")
	runner=${runner#bench-}

	if ! ls "$d"/*.md >/dev/null 2>&1; then
		missing+=("$runner")
		continue
	fi
	found=$((found + 1))

	printf '\n---\n\n# %s\n\n' "$runner"
	if [ -s "$d/cpu.txt" ]; then
		printf '<details><summary>machine</summary>\n\n```\n'
		cat "$d/cpu.txt"
		printf '```\n\n</details>\n\n'
	fi
	for f in compare backends xxh64; do
		[ -s "$d/$f.md" ] || continue
		cat "$d/$f.md"
		printf '\n'
	done
done

if [ ${#missing[@]} -gt 0 ]; then
	printf '\n---\n\n## Runners with no results\n\n'
	for m in "${missing[@]}"; do printf -- '- %s\n' "$m"; done
fi

if [ "$found" -eq 0 ]; then
	echo "mkbenchmarks: no runner produced tables" >&2
	exit 1
fi
